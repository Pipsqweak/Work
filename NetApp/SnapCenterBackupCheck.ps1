<#
.SYNOPSIS
Checks NetApp VMware volume SMVI snapshots and makes sure the oldest backup isn't more than 8 days old and the newest backup isn't older than 2 days old.

.DESCRIPTION
This script connects to each CDOT cluster and 7-Mode node and gathers configuration information. This information can
    be used to rebuild in the event of a DR scenario.

.EXAMPLE
.\netappConfigBackup.ps1

.PARAMETER $logFileBasePath
This parameter defines the base path for the log output file of the script. (Where logs will be written)

.PARAMETER $logFileBaseName
The parameter defines the root of the scripts log output file name.

.PARAMETER $sendTo
This parameter defines the email destination for the standard script email output.

.PARAMETER $from
This parameter defines the from address for emails generated by the script.

.PARAMETER $smtpServer
This parameter defines the SMTP server to be used when the script sends an email.

.PARAMETER $cdotClusterListFile
This parameter defines the text file that contains all of the CDOT clusters to pull data from.

.PARAMETER $logFileRetentionDays
This parameter defines how long this script's log files are retained.

.PARAMETER $dataFileRetentionDays
This parameter defines how long the output data files from this script are kept.

.PARAMETER $backupAgeThreshold
This parameter defines the age upon which the script will alert for orphaned backup snapshots.

.PARAMETER $newestBackupDaysThreshold
This parameter defines the age upon which the script will alert that the most recent backup is too old and the previous backup job must have failed or have not run.

