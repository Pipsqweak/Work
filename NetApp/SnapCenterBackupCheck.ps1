Function Connect-Cluster
{
    Param
    (
        $clusters
    )

    foreach ($cluster in $clusters)
    {
        Out-LogFile "Connecting to CDOT cluster $cluster."
        $connection = Connect-NcController -Name $cluster

        if ($connection)
        {
            [void]$cdotConnectionArrayList.Add($connection)
        } `
        else
        {
            Out-LogFile "FAILURE: Could not connect to $cluster."
            Write-Host "FAILURE: Could not connect to $cluster."
            $Script:failMessages += "FAILURE: Could not connect to $cluster.`n"
        }

        $connection = $null
    }
}

if (!(Get-Module -Name DataONTAP))
{
    Import-Module DataONTAP
}


if (Test-Path -Path $cdotClusterListFile)
{
    #Confgure HTML settings
    $html = "<style>"
    $html = $html + "BODY{background-color:White;}"
    $html = $html + "TABLE{border-width: 1px;border-style: solid;border-color: black;border-collapse: collapse;}"
    $html = $html + "TH{border-width: 1px;padding: 5px;border-style: solid;border-color: black;background-color: green}"
    $html = $html + "TD{border-width: 1px;padding: 5px;text-align: center;border-style: solid;border-color: black;background-color: Silver}"
    $html = $html + "</style>"

    $cdotConnectionArrayList = New-Object System.Collections.ArrayList
    $snapshotsToReport = [System.Collections.Generic.List[System.Object]]::new()
    $cdotClusterList = Get-Content -Path $cdotClusterListFile

    # We don't care about volumes which match the follow...
    $volumesToIgnoreRegex = "^(JP_)|(ROOT_)|(vol0)|(SMD_)|(SL_)"

    foreach ($cluster in $cdotClusterList)
    {
        Connect-Cluster $cluster
    }

    # Get all snapshots named "SnapCenterBkp*" from all volumes and exclude the ones we want to ignore.
    $snapShots = Get-NcSnapshot -Controller $cdotConnectionArrayList -SnapName "SnapCenterBkp*" -Volume "*vmware*" | Where-Object { ($_.Volume -notmatch $volumesToIgnoreRegex) }

    # Now incrementally group snapshots by controller...
    $snapShotsByController = $snapShots | Group-Object -Property NcController
    $a = 0
    while($a -lt $snapShotsByController.Length)
    {
        # ... then group by vserver
        $snapshotsByControllerAndVServer = $snapShotsByController[$a].Group | Group-Object VServer
        $b = 0
        while($b -lt $snapshotsByControllerAndVServer.Length)
        {
            # ... and finally, group by volume.
            $snapshotsByControllerVServerAndVolume = $snapshotsByControllerAndVServer[$b].Group | Group-Object -Property Volume

            # Now, for each volume, find stale and orphaned snapshots and add them to the list of snapshot to include in the report.
            $c = 0
            while($c -lt $snapshotsByControllerVServerAndVolume.Length)
            {
                # Get the newest snapshot for the volume and determine if it is more than $newestBackupDaysThreshold days old -- This will be the most recent, but stale snapshot, signalling a missed backup.
                $staleSnapshots = @($snapshotsByControllerVServerAndVolume[$c].Group | Sort-Object -Descending -Property Created | Select-Object -First 1 | Where-Object { ($currentDate - $_.Created).TotalDays -gt $newestBackupDaysThreshold } )
                $staleSnapshots.ForEach({
                    $snapshotsToReport.Add($_)
                    Out-LogFile ("Most recent backup is too old. Assuming failure on volume {0}:{1}:{2}. Snapshot: {3}, created {4}." -f @($_.NcController.Name, $_.VServer, $_.Volume, $_.Name, $_.Created))
                })

                # Get all snapshots for the volume which are more than $backupAgeThreshold days old -- These are snapshots which SnapCenter failed to clean up.
                $orphanedSnapshots = @($snapshotsByControllerVServerAndVolume[$c].Group | Where-Object { ($currentDate - $_.Created).TotalDays -gt $backupAgeThreshold })
                $orphanedSnapshots.ForEach({
                    $snapshotsToReport.Add($_)
                    Out-LogFile ("Orphaned snapshot found on volume {0}:{1}:{2}. Snapshot: {3}, created {4}, age: {5} days." -f @($_.NcController.Name, $_.VServer, $_.Volume, $_.Name, $_.Created, ($currentDate - $_.Created).TotalDays))
                })

                $c++
            }
            $b++
        }
        $a++
    }

    # If there are any missing or orphaned snapshots, then send a report.
    if($snapshotsToReport.Count -gt 0)
    {
        Out-LogFile ("Sending VM backup report to {0} using server {1}." -f @($sendTo, $smtpServer))

        # create the report email message object
        $reportMessage = New-Object System.Net.Mail.MailMessage $from, $sendTo

        #Create the SMTP client object.
        $smtp = New-Object Net.Mail.SmtpClient($smtpServer)

        $reportMessage.Subject = "VM Backup report for {0}" -f @($currentDate.ToString("M/d/yyyy"))
        $reportMessage.Body = $snapshotsToReport | Select-Object @{N='Status';E={ if(($currentDate - $_.Created).TotalDays -gt $backupAgeThreshold) { "Orphaned" } else { "Missed" }}},Vserver, Volume, @{N='Age-Days';E={($currentDate - $_.Created).TotalDays.ToString("N2")}},@{N='Snapshot-Name';E={$_.Name}}, Created | Sort-Object Status, Vserver, Volume, Age-Days | ConvertTo-Html -Head $html
        $reportMessage.IsBodyHTML = $true

        #Send it!
        $smtp.Send($reportMessage)
        $smtp.Dispose()
    } `
    else
    {
        # Nothing, no report to send.
    }
} `
else
{
    Out-Logfile "FAILURE: Could not find the cdot file, $cdotClusterListFile."
    Write-Host "FAILURE: Could not find the cdot file, $cdotClusterListFile."
    $failMessages += "FAILURE: Could not find the cdot file, $cdotClusterListFile.`n"
}
